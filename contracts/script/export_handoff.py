"""Export/check the current compiled ABIs and the local Anvil event handoff.

Run from contracts/. This never assigns a Sepolia address or claims deployment.
"""

import argparse
import hashlib
import json
from pathlib import Path
import shutil
import subprocess


CONTRACTS = ("PredictionMarket", "ResolverRegistry", "MarketPricing", "ACONTestToken")
REQUIRED_EVENTS = {
    "FixtureRegistered", "MarketCreated", "TradeExecuted", "SellExecuted", "MarketClosed",
    "OutcomeProposed", "OutcomeChallenged", "ResolverSelectionRequested", "ResolverCommitteeSelected",
    "ResolverSelectionRequestFailed",
    "VRFFulfillmentIgnored", "ResolverVoteCast", "MarketFinalized", "MarketVoided", "PayoutClaimed", "CreatorSurplusWithdrawn",
}


def tool(name, *args):
    executable = shutil.which(name) or str(Path.home() / ".foundry/bin" / name)
    result = subprocess.run([executable, *args], capture_output=True, text=True, timeout=120)
    if result.returncode:
        raise RuntimeError(result.stderr or result.stdout)
    return result.stdout.strip()


def canonical(field):
    if field["type"].startswith("tuple"):
        return "(" + ",".join(canonical(child) for child in field["components"]) + ")" + field["type"][5:]
    return field["type"]


def display(field):
    kind = field["type"]
    if kind.startswith("tuple"):
        kind = field["internalType"].removeprefix("struct ").split(".")[-1]
    suffix = " indexed" if field.get("indexed") else ""
    return kind + suffix + (" " + field["name"] if field.get("name") else "")


def export(check=False):
    root = Path(__file__).resolve().parents[2]
    destination = root / "deployments"
    source_files = [*[root / "contracts" / name for name in ("foundry.toml", "foundry.lock", "remappings.txt")],
                    *sorted((root / "contracts/src").glob("*.sol")),
                    *sorted((root / "contracts/lib/prb-math/src").rglob("*.sol"))]
    source_hashes = {str(path.relative_to(root)): hashlib.sha256(path.read_bytes()).hexdigest() for path in source_files}
    abis = {}
    metadata = {}
    for name in CONTRACTS:
        abi = json.loads(tool("forge", "inspect", name, "abi", "--json"))
        assert isinstance(abi, list)
        encoded = (json.dumps(abi, indent=2) + "\n").encode()
        runtime = tool("forge", "inspect", name, "deployedBytecode")
        size = (len(runtime) - 2) // 2
        assert size <= 24_576, f"{name} exceeds EIP-170: {size}"
        path = destination / "abi" / (name + ".abi.json")
        if check:
            assert path.read_bytes() == encoded, f"Stale compiled ABI: {path}"
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(encoded)
        abis[name] = abi
        metadata[name] = {"abi_path": str(path.relative_to(root)), "abi_sha256": hashlib.sha256(encoded).hexdigest(),
                          "compiled_runtime_bytes": size,
                          "runtime_template_sha256": hashlib.sha256(bytes.fromhex(runtime[2:])).hexdigest(),
                          "deployment_address": None}
    assert REQUIRED_EVENTS <= {entry.get("name") for entry in abis["PredictionMarket"] if entry["type"] == "event"}
    state = {
        "status": "LOCAL DRAFT - NOT DEPLOYED OR TEAM-FROZEN",
        "target_chain_id": 11155111,
        "compiler": "solc 0.8.24; optimizer 200; via_ir true",
        "source_sha256": source_hashes,
        "contracts": metadata,
        "release_gates": ["exact ABI/event/fixture-key consumer review", "Matthew economic proof and payout sign-off",
                          "2-of-3 team Safe and funded VRF v2.5 subscription", "ten resolver-only Sepolia addresses",
                          "fresh Sepolia deployment, completed Safe roles/ownership, real VRF and transaction smoke"],
    }
    if check:
        recorded = json.loads((destination / "build.json").read_text())
        assert recorded == state, "Stale draft build/source hashes; regenerate after code changes"
    else:
        (destination / "build.json").write_text(json.dumps(state, indent=2) + "\n")

    lines = ["# Generated contract ABI reference", "", "**Local implementation draft; consumer review and Matthew's economic sign-off are still required.**",
             "", "Generated by `contracts/script/export_handoff.py` from the exact compiled artifacts.",
             "The current JSON ABIs are in `deployments/abi/` and source hashes in `deployments/build.json`. No new Sepolia deployment is asserted.",
             "", "`uint8` enum ordering and economic units are defined in [CONTRACT_ABI.md](CONTRACT_ABI.md).",
             "Tuple field order is part of the ABI. Pricing/math errors propagate from MarketPricing; clients should include its error ABI when decoding market reverts.", ""]
    tuples = {}
    for name, abi in abis.items():
        lines += ["## " + name, "", "### Functions", "", "| Function | Mutability | Returns |", "|---|---|---|"]
        for entry in abi:
            for field in entry.get("inputs", []) + entry.get("outputs", []):
                _collect_tuples(field, tuples)
            if entry["type"] not in {"function", "constructor"}:
                continue
            signature = entry.get("name", "constructor") + "(" + ", ".join(display(field) for field in entry["inputs"]) + ")"
            output = ", ".join(display(field) for field in entry.get("outputs", [])) or "—"
            lines.append(f"| `{signature}` | {entry['stateMutability']} | `{output}` |")
        lines += ["", "### Events (indexed positions explicit)", ""]
        for entry in abi:
            if entry["type"] == "event":
                lines.append("- `" + entry["name"] + "(" + ", ".join(display(field) for field in entry["inputs"]) + ")`")
        lines += ["", "### Errors", ""]
        for entry in abi:
            if entry["type"] == "error":
                lines.append("- `" + entry["name"] + "(" + ", ".join(display(field) for field in entry["inputs"]) + ")`")
        lines.append("")
    lines += ["## Tuple layouts", ""]
    for name, fields in tuples.items():
        lines += ["### " + name, "", "| Position | Field |", "|---:|---|"]
        lines += [f"| {i} | `{display(field)}` |" for i, field in enumerate(fields)]
        lines.append("")
    reference = root / "docs/agent/interfaces/CONTRACT_ABI_REFERENCE.md"
    reference_text = "\n".join(lines).rstrip() + "\n"
    if check:
        assert reference.read_text() == reference_text, "Stale generated ABI reference"
        fixtures = json.loads((destination / "event-fixtures.anvil.json").read_text())
        assert fixtures["chain_id"] == 31337
        assert fixtures["abi_sha256"] == metadata["PredictionMarket"]["abi_sha256"], "Event fixtures use stale ABI"
        events = {entry["name"]: entry for entry in abis["PredictionMarket"] if entry["type"] == "event"}
        missing_events = REQUIRED_EVENTS - {entry["event_name"] for entry in fixtures["fixtures"]}
        assert not missing_events, f"Missing required event examples: {', '.join(sorted(missing_events))}"
        for sample in fixtures["fixtures"]:
            event = events[sample["event_name"]]
            signature = event["name"] + "(" + ",".join(canonical(field) for field in event["inputs"]) + ")"
            assert sample["signature"] == signature
            assert sample["raw_log"]["topics"][0] == tool("cast", "keccak", signature)
            assert sample["nonindexed_values_in_abi_order"] == decode_event_data(event, sample["raw_log"])
        print("PASS: ABIs, runtime templates, source hashes, reference and event examples match the draft; runtime sizes fit EIP-170")
        return
    reference.write_text(reference_text)

    evidence_path = Path("cache/verification/anvil-smoke.json")
    if not evidence_path.exists():
        raise RuntimeError("Run script/smoke.py --start-anvil before exporting the event handoff")
    else:
        evidence = json.loads(evidence_path.read_text())
        assert evidence["chain_id"] == 31337 and evidence.get("logs"), "Rerun the updated Anvil smoke for event evidence"
        fixtures = []
        for entry in abis["PredictionMarket"]:
            if entry["type"] != "event":
                continue
            signature = entry["name"] + "(" + ",".join(canonical(field) for field in entry["inputs"]) + ")"
            topic = tool("cast", "keccak", signature)
            matching = [log for log in evidence["logs"] if log["address"].lower() == evidence["market"].lower() and log["topics"][0] == topic]
            if not matching:
                continue
            log = matching[0]
            decoded = decode_event_data(entry, log)
            fixtures.append({"event_name": entry["name"], "signature": signature, "raw_log": log,
                             "nonindexed_values_in_abi_order": decoded})
        missing_events = REQUIRED_EVENTS - {entry["event_name"] for entry in fixtures}
        assert not missing_events, f"Missing required event examples: {', '.join(sorted(missing_events))}"
        (destination / "event-fixtures.anvil.json").write_text(json.dumps({"chain_id": 31337,
            "source": "Local contract-only Anvil smoke; VRF is an explicit mock, not live Chainlink",
            "abi_sha256": metadata["PredictionMarket"]["abi_sha256"], "fixtures": fixtures}, indent=2) + "\n")
        (destination / "anvil-summary.json").write_text(json.dumps({"chain_id": 31337, "journeys": evidence["journeys"],
            "successful_transactions": len(evidence["transactions"]), "observed_head": evidence["observed_head"],
            "safe_checkpoint_at_depth_two": evidence["safe_checkpoint_at_depth_two"],
            "scope": "Contract journeys only; frontend/backend integration and real VRF/Safe release verification remain separate"}, indent=2) + "\n")
    print("Exported exact draft ABIs, source hashes, interface reference, and available Anvil event fixtures")


def decode_event_data(event, log):
    plain = [field for field in event["inputs"] if not field["indexed"]]
    assert len(log["topics"]) == 1 + sum(field["indexed"] for field in event["inputs"])
    if not plain:
        assert log["data"] == "0x"
        return []
    decoded = json.loads(tool("cast", "abi-decode", "--json", "f()(" + ",".join(canonical(field) for field in plain) + ")", log["data"]))
    if isinstance(decoded, dict):
        assert decoded["success"]
        decoded = decoded["data"]
    return decoded


def _collect_tuples(field, tuples):
    if not field["type"].startswith("tuple"):
        return
    name = field["internalType"].removeprefix("struct ").split(".")[-1].split("[")[0]
    tuples[name] = field["components"]
    for component in field["components"]:
        _collect_tuples(component, tuples)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    export(parser.parse_args().check)
