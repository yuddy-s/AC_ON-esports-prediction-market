"""Independent Decimal reference vectors for mathematical LMSR pricing.

Uses the direct real-valued log-sum-exp formula, not the Solidity interval algorithm.
All integer results must agree at 160 and 220 digits before being exported.
Run from contracts/: python3 script/pricing_reference.py [--check]
"""

import argparse
from decimal import Decimal, localcontext, ROUND_CEILING, ROUND_FLOOR
from pathlib import Path
import random
import shutil
import subprocess


WAD = 10**18
B = 50 * WAD
MAX_QUANTITY = 2000 * WAD
SCALE = 10**72


def evaluate(yes, no, shares, precision):
    with localcontext() as context:
        context.prec = precision
        b = Decimal(B)
        before_difference = abs(yes - no)
        after_difference = abs(yes + shares - no)
        if before_difference == after_difference:
            # Exact reflection identity: equal correction terms cancel symbolically.
            delta = Decimal(max(yes + shares, no) - max(yes, no))
        else:
            before = b * ((Decimal(yes) / b).exp() + (Decimal(no) / b).exp()).ln()
            after = b * ((Decimal(yes + shares) / b).exp() + (Decimal(no) / b).exp()).ln()
            delta = after - before
        floor = int(delta.to_integral_value(rounding=ROUND_FLOOR))
        ceil = int(delta.to_integral_value(rounding=ROUND_CEILING))
        return floor, ceil


def correction(difference, precision):
    with localcontext() as context:
        context.prec = precision
        value = (Decimal(1) + (-Decimal(difference) / Decimal(B)).exp()).ln() * Decimal(SCALE)
        return int(value.to_integral_value(rounding=ROUND_FLOOR))


def generate():
    cases = [
        (40 * WAD, 50 * WAD, 10 * WAD),  # Reported 464-base-unit discrepancy.
        (0, 0, 10 * WAD),  # Reverse trade would profit if only sell pricing changed.
        (1900 * WAD, 0, 100 * WAD),
        (0, 2000 * WAD, 100 * WAD),
        (0, 2000 * WAD, 1),
        (1999 * WAD, 0, 1),
        (49 * WAD, 50 * WAD, 2 * WAD),
        (0, 1, 2),
        (0, 0, 2),
        (0, 2, 2),
        (MAX_QUANTITY - 1, MAX_QUANTITY, 1),
        (MAX_QUANTITY - 100 * WAD, MAX_QUANTITY, 100 * WAD),
    ]
    for imbalance in range(-3, 4):
        for shares in (1, 2, 3, 9):
            cases.append((50 * WAD + imbalance, 50 * WAD, shares))
    rng = random.Random(416)
    for _ in range(32):
        yes = rng.randrange(MAX_QUANTITY)
        no = rng.randrange(MAX_QUANTITY + 1)
        shares = rng.randrange(1, min(100 * WAD, MAX_QUANTITY - yes) + 1)
        cases.append((yes, no, shares))
    cases = list(dict.fromkeys(cases))
    lines = [
        "// SPDX-License-Identifier: MIT",
        "pragma solidity 0.8.24;",
        "",
        "// Generated by script/pricing_reference.py; do not edit by hand.",
        "// Direct Decimal log-sum-exp results agree at 160 and 220 digits.",
        "library PricingVectors {",
        "    struct Vector {",
        "        uint256 yes;",
        "        uint256 no;",
        "        uint256 shares;",
        "        uint256 floorAmount;",
        "        uint256 ceilAmount;",
        "    }",
        "",
        "    struct Correction {",
        "        uint256 difference;",
        "        uint256 floorAtScale;",
        "    }",
        "",
        "    function trades() internal pure returns (Vector[] memory data) {",
        f"        data = new Vector[]({len(cases)});",
    ]
    differences = {0, MAX_QUANTITY}
    for index, (yes, no, shares) in enumerate(cases):
        floor, ceil = evaluate(yes, no, shares, 160)
        assert (floor, ceil) == evaluate(yes, no, shares, 220), "Reference precision disagreement"
        lines.append(f"        data[{index}] = Vector({yes}, {no}, {shares}, {floor}, {ceil});")
        differences.update((abs(yes - no), abs(yes + shares - no)))
    lines += ["    }", "", "    function corrections() internal pure returns (Correction[] memory data) {",
              f"        data = new Correction[]({len(differences)});"]
    for index, difference in enumerate(sorted(differences)):
        value = correction(difference, 160)
        assert value == correction(difference, 220), "Correction precision disagreement"
        lines += [f"        data[{index}] = Correction(", f"            {difference},",
                  f"            {value}", "        );"]
    lines += ["    }", "}"]
    # Formatting is independent of the Decimal calculation and uses the repository's pinned Forge.
    forge = shutil.which("forge") or str(Path.home() / ".foundry/bin/forge")
    formatted = subprocess.run([forge, "fmt", "--raw", "-"], input="\n".join(lines) + "\n",
                               capture_output=True, text=True, check=True, timeout=30)
    return formatted.stdout, len(cases), len(differences)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    content, trades, corrections = generate()
    destination = Path(__file__).resolve().parents[1] / "test/PricingVectors.sol"
    if args.check:
        assert destination.read_text() == content, "Stale independent pricing vectors"
    else:
        destination.write_text(content)
    print(f"PASS: {trades} mathematical trade vectors and {corrections} correction bounds agree at 160/220 digits")
